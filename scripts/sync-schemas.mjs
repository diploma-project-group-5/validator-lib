// Copies the JSON Schemas this library validates against from the @lad/contracts package into
// src/generated (git-ignored), and records the contracts version. The schemas are an artifact of
// contracts, never edited here (ADR 2026-11-09).
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const contractsRoot = dirname(require.resolve('@lad/contracts/package.json'));
const out = new URL('../src/generated/', import.meta.url).pathname;

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'schemas'), { recursive: true });
for (const dir of ['events', 'validator']) {
  cpSync(join(contractsRoot, 'schemas', dir), join(out, 'schemas', dir), { recursive: true });
}
const { version } = JSON.parse(readFileSync(join(contractsRoot, 'package.json'), 'utf8'));
// The boundary imports the schemas as a module (no file reads at runtime), so a single-file bundle of
// the CLI works without a schemas directory next to it.
const read = (p) => JSON.parse(readFileSync(join(contractsRoot, 'schemas', p), 'utf8'));
const embed = {
  defs: read('events/defs.v1.json'),
  conflict: read('events/conflict.v1.json'),
  input: read('validator/validation.input.v1.json'),
  outcome: read('validator/validation.outcome.v1.json'),
};
writeFileSync(
  join(out, 'schemas.ts'),
  `// Generated by scripts/sync-schemas.mjs from @lad/contracts ${version} — do not edit.\n` +
    Object.entries(embed)
      .map(([name, schema]) => `export const ${name}Schema: object = ${JSON.stringify(schema)};\n`)
      .join(''),
);
writeFileSync(
  join(out, 'contracts-version.ts'),
  `// Generated by scripts/sync-schemas.mjs — do not edit.\nexport const CONTRACTS_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`schemas synced from @lad/contracts ${version}`);
